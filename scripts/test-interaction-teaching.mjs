import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const evidence = process.argv[2] || 'E:/codex/work/ty-bi-interaction-20260929'
await fs.mkdir(evidence,{recursive:true})
const browser = await chromium.launch({headless:true})
const page = await browser.newPage({viewport:{width:1800,height:1200}})
const errors=[], failures=[], requests=[]
page.on('pageerror',e=>errors.push(e.message))
page.on('response',r=>{if(r.url().includes('/api/')&&r.status()>=400)failures.push(`${r.status()} ${r.url()}`)})
page.on('request',r=>{if(r.url().includes('/execute')&&r.method()==='POST')requests.push(r.postDataJSON())})
try {
 await page.goto('http://127.0.0.1:5174/')
 await page.getByRole('button',{name:'交互教学',exact:true}).click()
 await page.getByRole('button',{name:'一键创建教学看板',exact:true}).click()
 await page.getByRole('dialog').waitFor({state:'hidden'})
 await page.getByRole('button',{name:'保存',exact:true}).click()
 await page.reload()
 await page.getByRole('button',{name:'预览',exact:true}).click()
 const source=page.locator('[data-component-id$="-source"]'), filtered=page.locator('[data-component-id$="-filtered"]')
 await source.locator('tbody tr').first().waitFor()
 await filtered.locator('tbody tr').filter({hasText:'2026-08'}).waitFor()
 const month=page.getByLabel('运行时筛选条件').locator('select').first()
 await month.selectOption('2026-02')
 await filtered.locator('tbody tr').filter({hasText:'2026-02'}).waitFor()
 await source.locator('tbody tr').filter({hasText:'2026-01'}).click()
 await filtered.locator('tbody tr').filter({hasText:'2026-01'}).waitFor()
 await page.getByRole('button',{name:'清除联动',exact:true}).click()
 await filtered.locator('tbody tr').filter({hasText:'2026-02'}).waitFor()
 await page.locator('[data-component-id$="-jump"]').click()
 await page.getByRole('tab',{name:/月份详情/}).waitFor()
 await page.locator('[data-component-id$="-detail-table"] tbody tr').filter({hasText:'2026-02'}).waitFor()
 await page.getByRole('button',{name:'返回',exact:true}).click()
 await source.locator('tbody tr').first().waitFor()
 await page.locator('[data-component-id$="-drill"] tbody tr').filter({hasText:'2026-01'}).click()
 await page.getByLabel('下钻面包屑').filter({hasText:'月份'}).waitFor()
 await page.locator('[data-component-id$="-detail-table"] tbody tr').filter({hasText:'2026-01'}).click()
 await page.getByLabel('下钻面包屑').filter({hasText:'指标值'}).waitFor()
 await page.screenshot({path:`${evidence}/drill.png`,fullPage:true})
 await page.getByTitle('返回上一下钻层级').last().click()
 await page.getByTitle('返回上一下钻层级').last().click()
 assert.equal(await page.getByLabel('下钻面包屑').count(),0)
 await page.getByRole('button',{name:'返回',exact:true}).click()
 await source.locator('tbody tr').first().waitFor()
 assert.ok(requests.some(r=>r.parameters?.month==='2026-01'))
 assert.ok(requests.some(r=>r.parameters?.month==='2026-02'))
 assert.deepEqual(errors,[]); assert.deepEqual(failures,[])
 await page.screenshot({path:`${evidence}/teaching.png`,fullPage:true})
 await fs.writeFile(`${evidence}/browser.json`,JSON.stringify({status:'PASS',checks:['one-click preset/save/reopen','parameter changes real local API result','row linkage and clear restore','navigation/back','two-level drill/breadcrumb/back'],errors,failures,requests},null,2))
 console.log('Interaction teaching E2E PASS')
} finally {await browser.close()}
