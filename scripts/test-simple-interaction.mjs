const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1800, height: 1200 } })
const errors = [], failures = [], requests = []
page.on('pageerror', e => errors.push(e.message))
page.on('response', r => { if (r.url().includes('/api/') && r.status() >= 400) failures.push(`${r.status()} ${r.url()}`) })
page.on('request', r => { if (r.url().includes('/execute') && r.method() === 'POST') requests.push(r.postDataJSON()) })
const panel = page.getByRole('dialog', { name: '事件配置', exact: true })
async function open(suffix) {
  await page.locator(`.design-component[data-component-id$="-${suffix}"]`).click()
  await page.getByRole('tab', { name: '交互', exact: true }).click()
  await page.getByRole('button', { name: '配置组件事件' }).click()
  if (await panel.getByLabel('简易触发方式').count()) await panel.getByLabel('简易触发方式').selectOption(suffix === 'jump' ? 'click' : 'rowClick')
  if (await panel.getByRole('button', { name: '编辑已有规则', exact: true }).count()) await panel.getByRole('button', { name: '编辑已有规则', exact: true }).click()
}
