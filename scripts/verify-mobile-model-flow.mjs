import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
const evidence = 'E:/codex/work/tybi-mobile-model-20261008'
await mkdir(evidence, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5174/')
  await page.getByRole('button', { name: '提示词样例', exact: true }).click()
  await page.getByRole('button', { name: '填入输出示例（非模型生成）' }).click()
  assert.match(await page.getByLabel('可复制门诊提示词').inputValue(), /80|部分|局部/)
  const response = page.getByLabel('模型返回 JSON')
  const plan = JSON.parse(await response.inputValue())
  plan.title = '跨模型门诊验收'
  await response.fill(JSON.stringify(plan))
  await page.getByRole('button', { name: '校验并添加到设计器' }).click()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  const stored = () => page.evaluate(() => { const w = JSON.parse(localStorage.getItem('medical-bi-designer-workspace-v3')); return JSON.parse(localStorage.getItem(`medical-bi-designer-dashboard-v3::${w.generation}::${w.activeDashboardId}`)) })
  const original = await stored()
  await page.getByRole('button', { name: '预览', exact: true }).click()
  await page.getByLabel('预览设备').selectOption('phone')
  await page.waitForFunction(() => document.querySelector('.interactive-canvas.mobile-preview')?.getBoundingClientRect().width === 390)
  await page.locator('article').filter({ hasText: '门诊收入构成（万元）' }).locator('canvas').first().waitFor()
  const boxes = await page.locator('.interactive-canvas > article').evaluateAll(articles => articles.map(article => { const b = article.getBoundingClientRect(); return { x: b.x, y: b.y, width: b.width, height: b.height } }).sort((a,b) => a.y-b.y))
  assert.ok(boxes.length > 8)
  for (let i = 0; i < boxes.length; i++) {
    assert.ok(boxes[i].width <= 366.1)
    if (i) assert.ok(boxes[i].y >= boxes[i-1].y + boxes[i-1].height - 1)
  }
  await page.screenshot({ path: `${evidence}/phone-preview.png`, fullPage: true })
  await page.locator('article').filter({ hasText: '科室门诊人次 · 固定 2026-08 的 8 科室样本（点击进入）' }).locator('tbody tr').first().click()
  await page.locator('article').filter({ hasText: '① 科室医生样本' }).locator('tbody tr').first().waitFor()
  await page.getByText('← 返回上级页面', { exact: true }).click()
  await page.getByRole('button', { name: '退出预览' }).click()
  assert.deepEqual(await stored(), original, '移动预览不能修改保存的坐标')
  await page.getByRole('button', { name: '批量调整 / 文字调整', exact: true }).click()
  const move = page.getByRole('region', { name: '批量移动组件' })
  await move.getByRole('checkbox').nth(2).check()
  await move.getByRole('checkbox').nth(3).check()
  await move.getByLabel('纵向位移').fill('20')
  await move.getByRole('button', { name: '预览整体移动' }).click()
  await page.getByRole('button', { name: '应用到当前看板' }).click()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  const moved = await stored()
  const changed = moved.pages[0].components.filter((c, i) => c.position.y !== original.pages[0].components[i].position.y)
  assert.equal(changed.length, 2)
  for (const c of changed) {
    const before = original.pages[0].components.find(item => item.id === c.id)
    assert.equal(c.position.y - before.position.y, 20)
    assert.deepEqual(c.dataConfig, before.dataConfig)
    assert.deepEqual(c.events, before.events)
  }
  await page.getByRole('button', { name: '撤销文字调整', exact: true }).click()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  assert.deepEqual((await stored()).pages, original.pages, '撤销后恢复全部页面配置')
  await page.reload()
  await page.getByLabel('移动端自适应').waitFor()
  assert.equal(await page.getByLabel('移动端自适应').isChecked(), true)
  await page.getByRole('button', { name: '预览', exact: true }).click()
  await page.getByLabel('预览设备').selectOption('desktop')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForFunction(() => document.querySelector('.interactive-canvas.mobile-preview')?.getBoundingClientRect().width <= 390)
  await page.screenshot({ path: `${evidence}/phone-auto.png`, fullPage: true })
  const overflow = await page.evaluate(() => ({ width: innerWidth, body: document.documentElement.scrollWidth }))
  assert.ok(overflow.body <= overflow.width + 1, JSON.stringify(overflow))
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ status: 'PASS', imported: 'local output example, no model API', mobile: true, navigation: true, groupMoveUndo: true, savedReopened: true, evidence }))
} finally { await browser.close() }
