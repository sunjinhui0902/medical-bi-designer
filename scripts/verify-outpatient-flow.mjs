import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import { readFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const base = process.env.TYBI_BASE_URL || 'http://127.0.0.1:5174/'
const evidence = new URL('../../work/tybi-outpatient-20260930/', import.meta.url)
await mkdir(evidence, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ acceptDownloads: true, viewport: { width: 1500, height: 1000 } })
  const errors = []
  const historicalRequests = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (/\/api\/knowledge\/hospital-model\//.test(request.url())) historicalRequests.push(request.url()) })
  await page.goto(base)
  await page.getByRole('button', { name: '打开看板管理' }).click()
  await page.getByRole('button', { name: '门诊运营分析 · 五页样例' }).click()
  await page.getByText('医院门诊总览', { exact: true }).first().waitFor()
  assert.match(await page.locator('body').innerText(), /医院门诊总览/)
  await page.getByRole('button', { name: '预览', exact: true }).click()
  const insight = page.locator('article').filter({ hasText: '同比变化提示 · 本地快照' })
  await insight.locator('tbody tr').first().waitFor()
  assert.equal(await insight.locator('tbody tr').count(), 3)
  assert.match(await insight.innerText(), /2025|去年同期|同比/)
  const visitMix = page.locator('article').filter({ hasText: '门诊 / 急诊人次构成' })
  const revenueMix = page.locator('article').filter({ hasText: '门诊收入构成（万元）' })
  await visitMix.locator('canvas').first().waitFor()
  await revenueMix.locator('canvas').first().waitFor()
  await visitMix.screenshot({ path: fileURLToPath(new URL('visit-mix.png', evidence)) })
  await revenueMix.screenshot({ path: fileURLToPath(new URL('revenue-mix.png', evidence)) })
  const sourceNote = page.locator('article').filter({ hasText: '口径与来源' })
  await sourceNote.screenshot({ path: fileURLToPath(new URL('source-note.png', evidence)) })
  const fullRank = page.locator('article').filter({ hasText: '科室门急诊人次前 20 · 点击进入科室分析' })
  await fullRank.locator('tbody tr').first().waitFor()
  assert.equal(await fullRank.locator('tbody tr').count(), 10)
  assert.match(await fullRank.getByRole('button', { name: /下载明细 CSV/ }).innerText(), /已加载 20 行/)
  await fullRank.locator('tbody tr').first().hover()
  assert.equal(await fullRank.locator('tbody tr').first().evaluate(row => getComputedStyle(row).cursor), 'pointer')
  await fullRank.getByRole('button', { name: '下一页', exact: true }).click()
  assert.match(await fullRank.locator('footer').innerText(), /2 \/ 2/)
  const rankDownloadPromise = page.waitForEvent('download')
  await fullRank.getByRole('button', { name: /下载明细 CSV/ }).click()
  const rankDownload = await rankDownloadPromise
  const rankCsv = await readFile(await rankDownload.path(), 'utf8')
  assert.equal(rankCsv.trim().split('\r\n').length, 21)
  await fullRank.screenshot({ path: fileURLToPath(new URL('full-department-rank.png', evidence)) })
  await page.screenshot({ path: fileURLToPath(new URL('hospital.png', evidence)), fullPage: true })
  await page.locator('select').first().selectOption('2025-08')
  await page.locator('article').filter({ hasText: '同比变化提示 · 本地快照' }).getByText('缺去年同期').first().waitFor()
  await fullRank.locator('tbody tr').first().waitFor()
  await page.waitForFunction(() => Array.from(document.querySelectorAll('article')).find(article => article.textContent.includes('科室门急诊人次前 20 · 点击进入科室分析'))?.querySelector('footer b')?.textContent === '1 / 2')
  assert.match(await fullRank.locator('tbody').innerText(), /2025-08/)
  assert.match(await page.locator('body').innerText(), /固定 2026-08 的 8 科室样本/)
  await page.locator('select').first().selectOption('2026-08')
  const hospitalTable = page.locator('article').filter({ hasText: '科室门诊人次 · 固定 2026-08 的 8 科室样本（点击进入）' })
  await hospitalTable.locator('tbody tr').first().click()
  const linked = page.locator('article').filter({ hasText: '① 科室医生样本' })
  await linked.locator('tbody tr').first().waitFor()
  assert.equal(await linked.locator('tbody tr').count(), 10)
  await page.screenshot({ path: fileURLToPath(new URL('department.png', evidence)), fullPage: true })
  await page.locator('article').filter({ hasText: '② 点击科室下钻' }).locator('tbody tr').first().click()
  await page.locator('article').filter({ hasText: '科室医生 · 点击行继续下钻' }).locator('tbody tr').first().click()
  const detail = page.locator('article').filter({ hasText: '当前医生门诊人次' })
  await detail.locator('tbody tr').first().waitFor()
  assert.equal(await detail.locator('tbody tr').count(), 1)
  const downloadPromise = page.waitForEvent('download')
  await detail.getByRole('button', { name: /下载明细 CSV/ }).click()
  const download = await downloadPromise
  const csv = await readFile(await download.path(), 'utf8')
  assert.match(csv, /医生编号/)
  assert.match(csv, /门诊人次/)
  await page.screenshot({ path: fileURLToPath(new URL('doctor-detail.png', evidence)), fullPage: true })
  for (const title of ['科室医生 · 点击行继续下钻', '① 科室医生样本', '同比变化提示 · 本地快照']) {
    await page.getByText('← 返回上级页面', { exact: true }).click()
    await page.locator('article').filter({ hasText: title }).locator('tbody tr').first().waitFor()
  }
  await page.getByRole('button', { name: '退出预览' }).click()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await page.reload()
  assert.match(await page.locator('body').innerText(), /门诊运营分析 · 本地样例/)
  await page.getByRole('button', { name: '预览', exact: true }).click()
  await page.locator('article').filter({ hasText: '门诊收入构成（万元）' }).locator('canvas').first().waitFor()
  await page.setViewportSize({ width: 900, height: 900 })
  await page.screenshot({ path: fileURLToPath(new URL('narrow.png', evidence)), fullPage: true })
  await page.getByRole('button', { name: '退出预览' }).click()
  await page.getByRole('button', { name: '打开看板管理' }).click()
  await page.getByRole('button', { name: '医院运营概览', exact: true }).click()
  await page.getByText('医院运营概览 · 本地模板', { exact: true }).first().waitFor()
  const beforeReopen = await page.evaluate(() => JSON.parse(localStorage.getItem('medical-bi-designer-workspace-v3')).dashboards.length)
  await page.getByRole('button', { name: '打开看板管理' }).click()
  await page.getByRole('button', { name: '医院运营概览', exact: true }).click()
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('medical-bi-designer-workspace-v3')).dashboards.length), beforeReopen)
  assert.deepEqual(historicalRequests, [])
  assert.equal(errors.length, 0, errors.join('\n'))
  console.log(JSON.stringify({ status: 'PASS', pages: 5, linkedDoctorRows: 10, detailRows: 1, csvBytes: csv.length, reloaded: true, evidence: fileURLToPath(evidence) }))
} finally { await browser.close() }
